/**
 * 根据文本语境和情绪，自动追加合适的颜文字。
 * 紧张刺激用 (°ω°)
 * 温暖感人用 (´▽`)
 * 神秘诡异用 (¬_¬)
 * 轻松愉快用 (＾▽＾)
 * 悲壮沉重用 (´;ω;`)
 * 日常平淡用 (´-`)
 * 惊喜震撼用 (⊙_⊙)
 * 浪漫温馨用 (♥ω♥)
 */

const KAOMOJI_MAP: Array<{ pattern: RegExp; kaomoji: string }> = [
  // 紧张 / 刺激 / 危险
  { pattern: /紧张|刺激|危险|危机|追杀|逃亡|战斗|搏斗|生死|恐惧|害怕|冷汗|窒息|绝望|崩溃|颤抖|尖叫/i, kaomoji: '(°ω°)' },
  // 温暖 / 感人 / 治愈
  { pattern: /温暖|感人|治愈|拥抱|微笑|温柔|感动|泪水|幸福|安心|守护|陪伴|希望|光明|救赎/i, kaomoji: '(´▽`)' },
  // 神秘 / 诡异 / 悬疑
  { pattern: /神秘|诡异|悬疑|谜|未知|阴影|黑暗|低语|幻觉|扭曲|异样|不祥|诡异|古怪|蹊跷|幽暗/i, kaomoji: '(¬_¬)' },
  // 轻松 / 愉快 / 欢乐
  { pattern: /轻松|愉快|欢乐|开心|大笑|玩笑|悠闲|惬意|阳光|明媚|欢快|喜悦|快乐|高兴|嘻嘻/i, kaomoji: '(＾▽＾)' },
  // 悲壮 / 沉重 / 悲伤
  { pattern: /悲壮|沉重|悲伤|牺牲|陨落|永别|诀别|哀悼|葬礼|哭泣|痛哭|心碎|遗憾|悔恨|苍凉|凄凉/i, kaomoji: '(´;ω;`)' },
  // 惊喜 / 震撼 / 震惊
  { pattern: /惊喜|震撼|震惊|不可思议|难以置信|惊叹|奇迹|壮观|宏伟|惊人|目瞪口呆/i, kaomoji: '(⊙_⊙)' },
  // 浪漫 / 温馨 / 甜蜜
  { pattern: /浪漫|甜蜜|爱意|告白|亲吻|拥抱|依偎|心动|约会|情侣|恋人|玫瑰|誓言/i, kaomoji: '(♥ω♥)' },
  // 日常 / 平淡
  { pattern: /日常|平淡|普通|寻常|安静|宁静|平和|悠然|闲适|漫步|踱步|沉默/i, kaomoji: '(´-`)' },
]

/**
 * 根据文本内容判断语境，追加合适的颜文字。
 * 如果文本末尾已有颜文字或标点符号，则先换行再追加。
 */
export function appendKaomoji(text: string): string {
  // 如果文本为空，直接返回
  if (!text) return text

  // 如果末尾已经有颜文字（包含括号的日文字符），不再追加
  if (/[（(][\u3040-\u309f\u30a0-\u30ff\u4e00-\u9fffω⊙¬_;^`♥][）)]$/.test(text.trim())) {
    return text
  }

  for (const { pattern, kaomoji } of KAOMOJI_MAP) {
    if (pattern.test(text)) {
      // 如果末尾不是换行，加一个空格再追加
      if (text.endsWith('\n')) {
        return text + kaomoji
      }
      return text + ' ' + kaomoji
    }
  }

  // 默认使用轻松愉快的颜文字
  return text + ' (＾▽＾)'
}
